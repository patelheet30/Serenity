-- Postgres schema, consolidated from the old SQLite migrations 001–005.
--
-- Discord snowflakes and unix timestamps are BIGINT: Postgres INTEGER is 32-bit.
-- No foreign keys: SQLite never enforced them, so existing data isn't guaranteed to
-- satisfy them (and warnings.case_id holds a case_number, not mod_cases.id).
-- Identity columns are BY DEFAULT so the SQLite import can keep its ids.

CREATE TABLE guild_config (
    guild_id          BIGINT PRIMARY KEY,
    is_enabled        BOOLEAN DEFAULT TRUE,
    default_threshold INTEGER DEFAULT 10,
    update_interval   INTEGER DEFAULT 30
);

CREATE TABLE channel_config (
    channel_id BIGINT PRIMARY KEY,
    guild_id   BIGINT NOT NULL,
    is_enabled BOOLEAN DEFAULT TRUE,
    threshold  INTEGER DEFAULT NULL
);

CREATE INDEX idx_channel_config_guild_enabled ON channel_config (guild_id, is_enabled);

CREATE TABLE message_activity (
    channel_id    BIGINT NOT NULL,
    timestamp     BIGINT NOT NULL,
    message_count INTEGER DEFAULT 1,
    PRIMARY KEY (channel_id, timestamp)
);

CREATE TABLE channel_patterns (
    channel_id          BIGINT,
    day_of_week         INTEGER,
    hour                INTEGER,
    avg_message_rate    DOUBLE PRECISION,
    stddev_message_rate DOUBLE PRECISION,
    sample_count        INTEGER,
    last_updated        BIGINT,  -- end of the last folded hour (unix), not the write time
    PRIMARY KEY (channel_id, day_of_week, hour)
);

CREATE TABLE slowmode_changes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id   BIGINT,
    old_value    INTEGER,
    new_value    INTEGER,
    reason       TEXT,
    message_rate DOUBLE PRECISION,
    confidence   DOUBLE PRECISION,
    timestamp    BIGINT
);

CREATE INDEX idx_slowmode_changes_channel_time ON slowmode_changes (channel_id, timestamp);

CREATE TABLE channel_analytics (
    channel_id     BIGINT,
    hour_timestamp BIGINT,
    total_messages INTEGER,
    unique_users   INTEGER,
    avg_slowmode   INTEGER,
    max_slowmode   INTEGER,
    PRIMARY KEY (channel_id, hour_timestamp)
);

CREATE TABLE slowmode_effectiveness (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id          BIGINT,
    applied_at          BIGINT,
    slowmode_value      INTEGER,
    message_rate_before DOUBLE PRECISION,
    message_rate_after  DOUBLE PRECISION,
    duration_seconds    INTEGER,
    was_effective       BOOLEAN
);

CREATE TABLE module_config (
    guild_id    BIGINT NOT NULL,
    module_type TEXT NOT NULL,
    is_enabled  BOOLEAN DEFAULT FALSE,
    settings    TEXT DEFAULT '{}',
    updated_at  BIGINT NOT NULL,
    PRIMARY KEY (guild_id, module_type)
);

CREATE TABLE mod_cases (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id          BIGINT NOT NULL,
    case_number       INTEGER NOT NULL,
    target_user_id    BIGINT NOT NULL,
    moderator_id      BIGINT NOT NULL,
    action            TEXT NOT NULL,
    reason            TEXT,
    duration_sections INTEGER,  -- sic; was TEXT in SQLite but always held seconds
    created_at        BIGINT NOT NULL,
    expires_at        BIGINT,
    is_active         BOOLEAN DEFAULT TRUE,
    UNIQUE (guild_id, case_number)
);

CREATE INDEX idx_mod_cases_target ON mod_cases (guild_id, target_user_id);
CREATE INDEX idx_mod_cases_created ON mod_cases (guild_id, created_at);
CREATE INDEX idx_mod_cases_expiring ON mod_cases (expires_at) WHERE action = 'timeout' AND is_active;

CREATE TABLE warnings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id     BIGINT NOT NULL,
    user_id      BIGINT NOT NULL,
    moderator_id BIGINT NOT NULL,
    reason       TEXT,
    case_id      INTEGER,  -- the case_number of the matching mod_cases row
    created_at   BIGINT NOT NULL,
    is_active    BOOLEAN DEFAULT TRUE
);

CREATE INDEX idx_warnings_user ON warnings (guild_id, user_id);

CREATE TABLE log_channels (
    guild_id         BIGINT NOT NULL,
    log_type         TEXT NOT NULL,
    channel_id       BIGINT,
    is_enabled       BOOLEAN DEFAULT TRUE,
    ignored_channels TEXT DEFAULT '[]',  -- legacy, superseded by log_ignores
    ignored_users    TEXT DEFAULT '[]',  -- legacy, superseded by log_ignores
    PRIMARY KEY (guild_id, log_type),
    CHECK (log_type IN ('member', 'message', 'voice', 'server', 'mod'))
);

CREATE TABLE log_ignores (
    guild_id    BIGINT NOT NULL,
    target_type TEXT NOT NULL,
    target_id   BIGINT NOT NULL,
    log_type    TEXT NOT NULL DEFAULT '*',
    created_at  BIGINT NOT NULL,
    PRIMARY KEY (guild_id, target_type, target_id, log_type),
    CHECK (target_type IN ('user', 'channel')),
    CHECK (log_type IN ('*', 'member', 'message', 'voice', 'server', 'mod'))
);
